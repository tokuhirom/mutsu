#!/usr/bin/env python3
"""Generate src/builtins/method_snapshot_index_gen.rs.

The index maps each owner of src/builtins/rakudo_method_tables.txt to the byte
ranges of its lines, so `method_introspection::facts()` does not have to scan the
1.2 MB snapshot for newlines on the first method call of every program (#14878).

    python3 -I scripts/gen-method-snapshot-index.py

`cargo test method_snapshot_index` fails when the committed table is stale.
"""
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parent.parent
text = (root / "src/builtins/rakudo_method_tables.txt").read_bytes()

owners = {}
pos = 0
while pos < len(text):
    end = text.find(b"\n", pos)
    if end == -1:
        end = len(text)
    line = text[pos:end]
    if not line.startswith(b"#"):
        fields = line.split(b"\t", 2)
        if len(fields) >= 2:
            owners.setdefault(fields[1].decode(), []).append((pos, end))
    pos = end + 1

out = [
    "// @generated by scripts/gen-method-snapshot-index.py from rakudo_method_tables.txt.",
    "// Do not edit; run the script after regenerating the snapshot.",
    "",
    "/// Each owner of the snapshot with the `(start, end)` byte ranges of its lines,",
    "/// sorted by owner for a binary search.",
    "pub(super) static OWNERS: &[(&str, &[(u32, u32)])] = &[",
]
for owner in sorted(owners, key=lambda o: o.encode()):
    ranges = ", ".join(f"({a}, {b})" for a, b in owners[owner])
    out.append(f'    ("{owner}", &[{ranges}]),')
out.append("];")
(root / "src/builtins/method_snapshot_index_gen.rs").write_text("\n".join(out) + "\n")
print(f"{len(owners)} owners", file=sys.stderr)
