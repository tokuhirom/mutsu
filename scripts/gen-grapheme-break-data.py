#!/usr/bin/env python3
"""Generate src/builtins/grapheme_break_data.rs from the Unicode Character Database.

Usage: scripts/gen-grapheme-break-data.py [VERSION] > src/builtins/grapheme_break_data.rs

Fetches GraphemeBreakProperty.txt, emoji-data.txt and DerivedCoreProperties.txt
(for Indic_Conjunct_Break) of the given Unicode VERSION (default 18.0.0) and
emits one table of (start, end, packed class) ranges, sorted and non-overlapping.
Packed class: bits 0-3 Grapheme_Cluster_Break, bit 4 Extended_Pictographic,
bits 5-6 InCB (0 none, 1 Linker, 2 Consonant, 3 Extend).
"""
import re
import sys
import urllib.request

version = sys.argv[1] if len(sys.argv) > 1 else "18.0.0"
base = f"https://www.unicode.org/Public/{version}/ucd/"

GCB = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator",
       "Prepend", "SpacingMark", "L", "V", "T", "LV", "LVT"]
INCB = {"Linker": 1, "Consonant": 2, "Extend": 3}


def fetch(path):
    with urllib.request.urlopen(base + path, timeout=60) as r:
        return r.read().decode("utf-8")


def entries(text, prop_filter=None):
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        fields = [f.strip() for f in line.split(";")]
        rng = fields[0]
        lo, _, hi = rng.partition("..")
        yield int(lo, 16), int(hi or lo, 16), fields[1:]


packed = [0] * 0x110000
for lo, hi, f in entries(fetch("auxiliary/GraphemeBreakProperty.txt")):
    v = GCB.index(f[0])
    for cp in range(lo, hi + 1):
        packed[cp] |= v
for lo, hi, f in entries(fetch("emoji/emoji-data.txt")):
    if f[0] == "Extended_Pictographic":
        for cp in range(lo, hi + 1):
            packed[cp] |= 0x10
for lo, hi, f in entries(fetch("DerivedCoreProperties.txt")):
    if f[0] == "InCB":
        for cp in range(lo, hi + 1):
            packed[cp] |= INCB[f[1]] << 5

ranges = []
start = 0
for cp in range(1, 0x110001):
    if cp == 0x110000 or packed[cp] != packed[start]:
        if packed[start]:
            ranges.append((start, cp - 1, packed[start]))
        start = cp

out = []
out.append(f"//! Grapheme-cluster-break data for Unicode {version}.")
out.append("//!")
out.append("//! GENERATED by scripts/gen-grapheme-break-data.py -- do not edit by hand.")
out.append("//! See `grapheme_break.rs` for the packing of the class byte.")
out.append("")
out.append("/// `(first, last, class)` ranges, sorted, non-overlapping; absent = 0.")
out.append("pub(crate) static TABLE: &[(u32, u32, u8)] = &[")
for i in range(0, len(ranges), 4):
    out.append("    " + " ".join(f"(0x{a:X}, 0x{b:X}, {c})," for a, b, c in ranges[i:i + 4]))
out.append("];")
print("\n".join(out))
