#!/usr/bin/env python3
"""Print additional 6.e CORE types relative to the same Rakudo's 6.d setting."""

from pathlib import Path
import subprocess


def names(generator: Path, preview: bool) -> set[str]:
    command = ["raku", str(generator)]
    if preview:
        command = [
            "raku", "-e", "use v6.e.PREVIEW; EVALFILE @*ARGS[0]", str(generator)
        ]
    result = subprocess.run(
        command, check=True, capture_output=True, text=True, timeout=30
    )
    return {
        line for line in result.stdout.splitlines()
        if line and not line.startswith("#")
    }


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    generator = root / "scripts/gen-core-type-names.raku"
    stable = names(generator, False)
    preview = names(generator, True)
    version = subprocess.run(
        ["raku", "-e", "print $*RAKU.compiler.version"],
        check=True, capture_output=True, text=True, timeout=30,
    ).stdout.strip()
    print("# Generated by scripts/gen-core-type-additions.py; do not edit.")
    print(f"# Rakudo {version}.")
    print("# Additional 6.e.PREVIEW types relative to the same Rakudo's 6.d setting.")
    for name in sorted(preview - stable):
        print(name)


if __name__ == "__main__":
    try:
        main()
    except subprocess.CalledProcessError as error:
        raise SystemExit(error.stderr or str(error)) from error
