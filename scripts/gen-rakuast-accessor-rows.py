#!/usr/bin/env python3
"""Generate static accessor rows from rakuast-accessor-owners.py's measurement.

Run the ignored dump_rakuast_accessor_schema test, measure it with Rakudo, then
pass that JSON as --owners. --list lists artifacts; --part prints one artifact
as JSON for the editor. --check verifies an already generated tree.
"""

import argparse
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent.parent
TARGET = Path("src/builtins/method_table/instances/rakuast_accessors")
CHUNK = 200


def artifacts(data):
    explicit = set(map(tuple, data["registered"]))
    facts = []
    for row in data["records"]:
        owner = row["owner"]
        # ADR-10723 section 6.92: mutsu implements spec hash capture aliases,
        # which Rakudo reserves. Its model flag is not Any's hash conversion.
        if (row["model"], row["method"], owner) == (
            "RakuAST::Regex::NamedCapture", "hash", "Any"
        ):
            owner = row["model"]
        if not owner:
            # An existing native model alias has its own storage spelling;
            # it is not claimed to be a class/method that Rakudo declares.
            if (row["model"], row["measured"], row["method"]) == (
                "RakuAST::Call::BlockMethod", "RakuAST::Call::TermAsMethod", "block"
            ):
                owner = row["model"]
            else:
                raise ValueError(f"unmeasured accessor: {row}")
        facts.append((row["model"], row["method"], owner))
    rows = sorted({(owner, method) for _, method, owner in facts} - explicit)
    output = {}
    chunks = []
    for index, start in enumerate(range(0, len(rows), CHUNK)):
        chunk = rows[start:start + CHUNK]
        chunks.append(f"rows_{index}")
        lines = ["// Generated by scripts/gen-rakuast-accessor-rows.py; do not edit.",
                 "use super::*;", "", "pub(super) const ROWS: &[MethodRow] = &["]
        for owner, name in chunk:
            if name == "compile-time-value" and owner not in (
                "RakuAST::VarDeclaration::Simple", "RakuAST::ParameterTarget::Var"
            ):
                expression = f'interp_row!("{owner}", "{name}", compiled_value)'
            elif name == "meta-object":
                expression = f'interp_row!("{owner}", "{name}", meta_object)'
            else:
                expression = f'row!("{owner}", "{name}")'
            lines.append(f"    {expression},")
        lines.append("];\n")
        output[str(TARGET / f"rows_{index}.rs")] = "\n".join(lines)
    declarations = "\n".join(f'#[path = "{name}.rs"]\nmod {name};' for name in chunks)
    parts = ", ".join(f"{name}::ROWS" for name in chunks)
    registry = f'''// Generated by scripts/gen-rakuast-accessor-rows.py; do not edit.
{declarations}

const PARTS: &[&[MethodRow]] = &[{parts}];
const N: usize = {len(rows)};
pub(super) static ROWS: [MethodRow; N] = flatten();

const fn flatten() -> [MethodRow; N] {{
    let mut rows = [PARTS[0][0]; N];
    let mut at = 0;
    let mut part = 0;
    while part < PARTS.len() {{
        let mut index = 0;
        while index < PARTS[part].len() {{
            rows[at] = PARTS[part][index];
            at += 1;
            index += 1;
        }}
        part += 1;
    }}
    rows
}}
'''
    output[str(TARGET / "registry.rs")] = registry
    hierarchy = {}
    for line in (ROOT / "src/rakuast/hierarchy.tsv").read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        hierarchy[fields[0]] = fields[2].split() if len(fields) > 2 else []
    chains = []
    for model, measured in sorted(data["classes"]):
        if measured not in hierarchy:
            raise ValueError(f"model type missing from measured hierarchy: {measured}")
        owners = ([model] if model != measured else []) + [measured] + hierarchy[measured]
        chains.append((model, [owner for owner in owners if owner not in ("Any", "Mu")]))
    owner_chunks = []
    for index, start in enumerate(range(0, len(chains), 20)):
        owner_chunks.append(f"owners_{index}")
        lines = ["// Generated by scripts/gen-rakuast-accessor-rows.py; do not edit.",
                 "use super::*;", "", "pub(super) const CHAINS: &[OwnerChain] = &["]
        for model, owners in chains[start:start + 20]:
            names = ", ".join(json.dumps(owner) for owner in owners)
            lines.append(f"    ({json.dumps(model)}, &[{names}]),")
        lines.append("];\n")
        output[str(TARGET / f"owners_{index}.rs")] = "\n".join(lines)
    declarations = "\n".join(f'#[path = "{name}.rs"]\nmod {name};' for name in owner_chunks)
    parts = ", ".join(f"{name}::CHAINS" for name in owner_chunks)
    output[str(TARGET / "owner_registry.rs")] = f'''// Generated by scripts/gen-rakuast-accessor-rows.py; do not edit.
{declarations}

const OWNER_PARTS: &[&[OwnerChain]] = &[{parts}];
const OWNER_N: usize = {len(chains)};
static OWNER_CHAINS: [OwnerChain; OWNER_N] = flatten_owners();

const fn flatten_owners() -> [OwnerChain; OWNER_N] {{
    let mut chains = [OWNER_PARTS[0][0]; OWNER_N];
    let mut at = 0;
    let mut part = 0;
    while part < OWNER_PARTS.len() {{
        let mut index = 0;
        while index < OWNER_PARTS[part].len() {{
            chains[at] = OWNER_PARTS[part][index];
            at += 1;
            index += 1;
        }}
        part += 1;
    }}
    chains
}}
'''
    output[str(TARGET / "owners.tsv")] = (
        f'# Generated from Rakudo {data["version"]}; model, method, declaring owner.\n'
        '# Existing model extensions: Call::BlockMethod.block; '
        'Regex::NamedCapture.hash (ADR-10723 section 6.92).\n'
        + "\n".join("\t".join(row) for row in sorted(set(facts))) + "\n"
    )
    for path, content in output.items():
        if path.endswith(".rs"):
            result = subprocess.run(
                ["rustfmt", "--edition", "2024", "--emit", "stdout", "--config", "skip_children=true"],
                input=content, capture_output=True, text=True, check=True,
            )
            output[path] = result.stdout
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--owners", type=Path, required=True)
    parser.add_argument("--part")
    parser.add_argument("--list", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = artifacts(json.loads(args.owners.read_text()))
    if args.list:
        print(json.dumps(list(files)))
    elif args.part:
        print(json.dumps(files[args.part]))
    elif args.check:
        differences = [name for name, content in files.items()
                       if not (ROOT / name).exists() or (ROOT / name).read_text() != content]
        if differences:
            raise SystemExit("generated accessor artifacts differ: " + ", ".join(differences))
        print(f"RakuAST accessor artifacts match ({len(files)} files)")
    else:
        parser.error("choose --list, --part, or --check")


if __name__ == "__main__":
    main()
