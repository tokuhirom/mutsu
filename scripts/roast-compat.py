#!/usr/bin/env python3
"""The one generator of mutsu's Roast compatibility figure (#19036).

The figure is counted against `roast/spectest.data`, the list of spec files
Rakudo runs ("a list of all spec tests that are expected to pass"), with the
`#?rakudo` fudge applied. The definition is in docs/roast-compatibility.md;
README, the site's stats.json and HISTORY.tsv all take it from here.

    roast-compat.py list
        The spectest.data files, as `roast/`-prefixed paths, one per line.
    roast-compat.py count [--pass-list FILE]
        "<pass> <total>": the spectest.data files that pass, out of all of them.
        A file passes when it is in FILE (a run's list of passing files, e.g.
        tmp/roast-pass.txt), or, without --pass-list, in roast-whitelist.txt
        (every whitelisted file passes `make roast` in CI).
    roast-compat.py stats-json
        The site's stats.json, from the whitelist.
    roast-compat.py readme [--check]
        Rewrite README.md's Roast status paragraph (between its
        `roast-compat` markers) from the whitelist and the last HISTORY.tsv
        row; --check only reports whether it is up to date (exit 1 if not).
"""

import argparse
import csv
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPECTEST = ROOT / "roast" / "spectest.data"
WHITELIST = ROOT / "roast-whitelist.txt"
HISTORY = ROOT / "HISTORY.tsv"
README = ROOT / "README.md"
BEGIN = "<!-- roast-compat:begin (generated by scripts/roast-compat.py readme) -->"
END = "<!-- roast-compat:end -->"


def spec_files() -> list[str]:
    """The spectest.data entries: the path before any `#` marker, deduplicated."""
    files = set()
    for line in SPECTEST.read_text(encoding="utf-8").splitlines():
        path = line.split("#", 1)[0].strip()
        if path:
            files.add(f"roast/{path}")
    return sorted(files)


def read_list(path: Path) -> set[str]:
    return {
        line.strip()
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip() and not line.startswith("#")
    }


def count(pass_list: Path | None) -> tuple[int, int]:
    spec = spec_files()
    passing = read_list(pass_list or WHITELIST)
    return sum(1 for f in spec if f in passing), len(spec)


def last_history_row() -> dict[str, str] | None:
    if not HISTORY.exists():
        return None
    with HISTORY.open(newline="", encoding="utf-8") as handle:
        rows = [row for row in csv.DictReader(handle, delimiter="\t") if row.get("date")]
    return rows[-1] if rows else None


def readme_paragraph() -> str:
    passed, total = count(None)
    text = (
        f"mutsu passes **{passed:,} of the {total:,}** test files Rakudo runs from\n"
        "the official [Roast](https://github.com/Raku/roast) spec suite\n"
        "(`roast/spectest.data`, with the `#?rakudo` fudge applied; a file counts\n"
        "only if every assertion it does not skip passes). The definition, and how\n"
        "it compares with other implementations' figures, is in\n"
        "[docs/roast-compatibility.md](docs/roast-compatibility.md)."
    )
    row = last_history_row()
    if row and row.get("subtests_pass") and row.get("subtests_total"):
        day = row["date"].split("T")[0]
        text += (
            f"\nA full run of the suite on {day} passed "
            f"**{int(row['subtests_pass']):,} of {int(row['subtests_total']):,}**\n"
            "subtests (`HISTORY.tsv`)."
        )
    return text


def rewrite_readme(check: bool) -> int:
    readme = README.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(BEGIN) + r"\n.*?\n" + re.escape(END), re.S)
    if not pattern.search(readme):
        print(f"README.md has no {BEGIN} ... {END} block", file=sys.stderr)
        return 2
    updated = pattern.sub(lambda _: f"{BEGIN}\n{readme_paragraph()}\n{END}", readme)
    if check:
        if updated != readme:
            print("README.md's Roast figure is stale: run scripts/roast-compat.py readme",
                  file=sys.stderr)
            return 1
        return 0
    if updated != readme:
        README.write_text(updated, encoding="utf-8")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("list")
    count_parser = sub.add_parser("count")
    count_parser.add_argument("--pass-list", type=Path)
    sub.add_parser("stats-json")
    readme_parser = sub.add_parser("readme")
    readme_parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    if args.command == "list":
        print("\n".join(spec_files()))
    elif args.command == "count":
        passed, total = count(args.pass_list)
        print(passed, total)
    elif args.command == "stats-json":
        passed, total = count(None)
        print(json.dumps({"roastPass": passed, "roastTotal": total,
                          "roastBasis": "spectest.data"}))
    elif args.command == "readme":
        return rewrite_readme(args.check)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
