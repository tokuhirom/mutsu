//! The rows of the built-in `X::` exception classes in the static class
//! catalogue (ADR-19206 slice 1, `builtin_class_catalogue`).
//!
//! One row per class: `name<TAB>parent<TAB>does,does,...` and a newline, sorted
//! by name (byte order; the catalogue checks this at compile time). `parent`
//! is the real superclass and drives `parents`/`mro`; `does` is the list of
//! composed marker roles, never folded into the MRO (ADR-0029).
//!
//! The rows are mechanically derived from real raku `.^mro` /
//! `.^roles(:!transitive)` output in `docs/data/x-exception-role-membership.tsv`
//! (`scripts/adr0029-capture-x-exception-data.py`). Do not hand-edit a row's
//! shape: regenerate it from the TSV, then keep the file sorted.
//!
//! A single string (rather than a table of `&str`) keeps the catalogue in
//! `.rodata` with no load-time relocations (ADR-19206 §2.2).
//!
//! Two rows are deliberate residues of ADR-0029 (#7545):
//!
//! - R4: `X::Comp` and `X::Syntax` are rows here *and* marker `RoleDef`s in
//!   the role table. In rakudo neither is a class, and `.HOW` already answers
//!   through the role. The class rows stay because two other rows name them as
//!   their parent, and the MRO walk resolves parents through these rows.
//! - R2: `X::TooLateForREPR` has `X::Comp` as both its parent and its composed
//!   role, rakudo's one "role-as-superclass pun" here
//!   (`X::TooLateForREPR.^mro` is `(X::TooLateForREPR X::Comp Exception Any Mu)`).
//!   The composed-role registries keep `X::Comp` out of its `does`-only set.
//!
//! The first rows of the old registration (`X::Comp`, `X::Value`, `X::Syntax`,
//! `X::Syntax::Signature`, `X::Role::Composition::Conflict`) are names raku
//! does not report as real `Exception` subtypes; they are kept unchanged.

