//! The built-in multi candidates of a core method, ranked against the
//! program's own (#12751).
//!
//! An `augment`ed `multi method` on a core type joins the dispatcher of the
//! built-in method it names, and Rakudo ranks it with the built-in candidates:
//! `augment class Any { multi method first(Callable $c) { ... } }` loses
//! `(1, 2, 3).first(* > 1)` to the built-in `first(Any: Callable:D $test, ...)`,
//! whose parameter is the narrower `Callable:D`. The method rows carry no
//! signatures, so the candidates come from a snapshot of Rakudo's own
//! (`rakudo_method_candidates.txt`, generated by
//! `scripts/gen-rakudo-method-candidates.raku`); each is turned into a body-less
//! [`MethodDef`] and ranked by the very walk that ranks the program's own
//! candidates ([`Interpreter::pick_method_winner`]).
//!
//! A candidate whose signature uses a type mutsu cannot match by name is left
//! out, so the program's candidate keeps winning as it did before this module.

use super::*;
use crate::ast::ParamDef;
use rustc_hash::FxHashMap;
use std::sync::OnceLock;

const SNAPSHOT: &str = include_str!("../builtins/rakudo_method_candidates.txt");

/// Marks a synthetic built-in candidate in [`MethodDef::role_origin`].
const BUILTIN_MARK: &str = "\0builtin-candidate";

/// One parameter of a snapshot candidate.
struct SigParam {
    flags: &'static str,
    ty: &'static str,
    smiley: char,
    name: &'static str,
}

type Candidate = Vec<SigParam>;

/// The snapshot, by `(owner, method)`. Parsed on first use.
// Cost: O(1) after the first call; that call is O(s), s = bytes of the snapshot.
fn table() -> &'static FxHashMap<(&'static str, &'static str), Vec<Candidate>> {
    static TABLE: OnceLock<FxHashMap<(&'static str, &'static str), Vec<Candidate>>> =
        OnceLock::new();
    TABLE.get_or_init(|| {
        let mut table = FxHashMap::default();
        for line in SNAPSHOT.lines().filter(|line| !line.starts_with('#')) {
            let mut fields = line.split('\t');
            let (Some(owner), Some(name)) = (fields.next(), fields.next()) else {
                continue;
            };
            let candidates: Vec<Candidate> = fields
                .map(|candidate| {
                    candidate
                        .split(' ')
                        .filter_map(|param| {
                            let mut parts = param.split('|');
                            Some(SigParam {
                                flags: parts.next()?,
                                ty: parts.next()?,
                                smiley: parts.next()?.chars().next()?,
                                name: parts.next()?,
                            })
                        })
                        .collect()
                })
                .collect();
            table.insert((owner, name), candidates);
        }
        table
    })
}

/// Whether the snapshot lists candidates for some method of `owner`, i.e. it
/// is a core type rather than a class the program declares.
// Cost: O(1) after the first call; that call is O(t), t = snapshot rows.
fn is_core_owner(owner: &str) -> bool {
    static OWNERS: OnceLock<rustc_hash::FxHashSet<&'static str>> = OnceLock::new();
    OWNERS
        .get_or_init(|| table().keys().map(|(owner, _)| *owner).collect())
        .contains(owner)
}

/// A parameter with every field at its blank value.
// Cost: O(1).
fn blank_param(name: &str) -> ParamDef {
    ParamDef { spans: Default::default(),
        trait_meta: Default::default(),
        type_capture: None,
        name: name.to_string(),
        default: None,
        multi_invocant: false,
        required: false,
        named: false,
        named_alias: false,
        slurpy: false,
        double_slurpy: false,
        onearg: false,
        sigilless: false,
        type_constraint: None,
        literal_value: None,
        sub_signature: None,
        where_constraint: None,
        traits: Vec::new(),
        optional_marker: false,
        outer_sub_signature: None,
        code_signature: None,
        is_invocant: false,
        shape_constraints: None,
        block_param: false,
        code: Default::default(),
        trait_args: Vec::new(),
    }
}

/// `ty` with its smiley, as a parameter's type constraint.
// Cost: O(t), t = type name length.
fn constraint(ty: &str, smiley: char) -> String {
    match smiley {
        'D' | 'U' => format!("{ty}:{smiley}"),
        _ => ty.to_string(),
    }
}

impl Interpreter {
    /// The synthetic method of `candidate`, declared on `owner`; `None` when
    /// one of its types is not one mutsu can match by name.
    // Cost: O(p) plus one type lookup per parameter, p = parameters.
    fn builtin_candidate_method(&self, owner: &str, candidate: &Candidate) -> Option<MethodDef> {
        let mut param_defs = Vec::with_capacity(candidate.len());
        let mut params = Vec::new();
        for param in candidate {
            let ty = param.ty;
            if !ty.is_empty()
                && (ty.contains(['(', '[', ':'])
                    || (!matches!(ty, "Any" | "Mu") && !self.is_resolvable_type(ty)))
            {
                return None;
            }
            let has = |flag: char| param.flags.contains(flag);
            let bare = param.name.trim_start_matches(['$', '*', ':', '\\']);
            let mut pd = if has('i') {
                let mut pd = blank_param("self");
                pd.is_invocant = true;
                let ty = if ty.is_empty() { owner } else { ty };
                pd.type_constraint = Some(constraint(ty, param.smiley));
                pd
            } else if has('c') {
                let mut pd = blank_param(bare.trim_start_matches('|'));
                pd.slurpy = true;
                pd.sigilless = true;
                pd
            } else if has('s') {
                let mut pd = blank_param(param.name.trim_start_matches('*'));
                pd.slurpy = true;
                pd
            } else if has('n') {
                let mut pd = blank_param(bare.trim_end_matches('!'));
                pd.named = true;
                pd.required = !has('?');
                pd
            } else {
                let name = if param.name.starts_with(['&', '@', '%']) {
                    param.name
                } else {
                    bare
                };
                let mut pd = blank_param(name);
                pd.optional_marker = has('?');
                pd
            };
            if !has('i') && !ty.is_empty() {
                pd.type_constraint = Some(constraint(ty, param.smiley));
            }
            params.push(pd.name.clone());
            param_defs.push(pd);
        }
        Some(MethodDef {
            value_prototype: None,
            syms: Default::default(),
            lexical_package: Symbol::intern(owner),
            params,
            param_defs,
            body: std::sync::Arc::new(Vec::new()),
            is_rw: false,
            is_raw: false,
            is_private: false,
            is_multi: true,
            is_my: false,
            role_origin: Some(BUILTIN_MARK.to_string()),
            original_role: None,
            return_type: None,
            compiled_code: None,
            compiled_fns: None,
            delegation: None,
            is_default: false,
            deprecated_message: None,
            is_submethod: false,
            is_hidden_from_backtrace: false,
            captured_env: None,
            source_file: None,
            role_param_bindings: None,
            nested_capture_index: None,
            captured_readonly: None,
            routine_cell: Default::default(),
        })
    }

    /// Whether a built-in candidate of `method` outranks the program's own
    /// winner for `target.method(|args)`: Rakudo ranks an `augment`ed `multi`
    /// with the built-in ones, so one whose parameters are no narrower than a
    /// built-in candidate that binds the same arguments never takes the call
    /// (a tie goes to the built-in, which is declared first).
    // Cost: O((m + b)^2 * h + (m + b) * p) for the ranking, m = user matches,
    // b = built-in matches; O(1) when the type has no built-in candidates.
    pub(crate) fn builtin_candidate_outranks_user(
        &mut self,
        target: &Value,
        class_name: &str,
        method: &str,
        args: &[Value],
    ) -> bool {
        let mro = self.class_mro(class_name);
        let mut builtin: Vec<(usize, Symbol, MethodDef)> = Vec::new();
        for (level, owner) in mro.iter().enumerate() {
            let folded =
                crate::builtins::builtin_type_methods::canonical_builtin_owner(owner.as_str());
            let owner_name = if folded.is_empty() {
                owner.as_str()
            } else {
                folded
            };
            let Some(candidates) = table().get(&(owner_name, method)) else {
                continue;
            };
            for candidate in candidates {
                if let Some(def) = self.builtin_candidate_method(owner_name, candidate) {
                    builtin.push((level, *owner, def));
                }
            }
        }
        if builtin.is_empty() {
            return false;
        }
        // The level of the most derived class that declares the method: a
        // user candidate above it is not a candidate of the receiver's
        // dispatcher at all.
        let declared_level = mro.iter().position(|owner| {
            let folded =
                crate::builtins::builtin_type_methods::canonical_builtin_owner(owner.as_str());
            let owner = if folded.is_empty() {
                owner.as_str()
            } else {
                folded
            };
            crate::builtins::method_introspection::native_method_declared(owner, method)
        });
        let mut user: Vec<(usize, Symbol, MethodDef)> = Vec::new();
        for (level, owner) in mro.iter().enumerate() {
            if declared_level.is_some_and(|declared| level > declared) {
                continue;
            }
            let overloads = self
                .registry()
                .get_method_overloads(owner.as_str(), method);
            for def in overloads.iter().flatten() {
                // A class the program declares owns its method: only a core
                // type's `augment` joins the built-in dispatcher (a `CArray`
                // multi ranked against `Any.ASSIGN-POS` would leave the call
                // to a built-in row the instance cannot run).
                if !is_core_owner(owner.as_str()) {
                    return false;
                }
                if !def.is_private && def.is_multi {
                    user.push((level, *owner, def.clone()));
                }
            }
        }
        if user.is_empty() {
            return false;
        }
        let bound = |this: &mut Self, entries: Vec<(usize, Symbol, MethodDef)>| {
            let mut matched = Vec::new();
            for (level, owner, def) in entries {
                if this.method_args_match_for_invocant(class_name, &def, args, None, Some(target)) {
                    matched.push((level, owner, def));
                }
            }
            matched
        };
        let builtin = bound(self, builtin);
        if builtin.is_empty() {
            return false;
        }
        let user = bound(self, user);
        if user.is_empty() {
            return false;
        }
        // MRO order, the built-in candidates ahead of the program's at one
        // level (they were declared first).
        let mut matches: Vec<(usize, u8, Symbol, MethodDef)> = Vec::new();
        matches.extend(builtin.into_iter().map(|(l, o, d)| (l, 0, o, d)));
        matches.extend(user.into_iter().map(|(l, o, d)| (l, 1, o, d)));
        matches.sort_by_key(|(level, kind, ..)| (*level, *kind));
        let matches: Vec<(Symbol, MethodDef)> =
            matches.into_iter().map(|(_, _, o, d)| (o, d)).collect();
        let saved_ambiguous = self.dispatch.dispatch_ambiguous;
        let winner = self.pick_method_winner(&mro, args, Some(target), matches, Vec::new());
        self.dispatch.dispatch_ambiguous = saved_ambiguous;
        winner.is_some_and(|(_, def)| def.role_origin.as_deref() == Some(BUILTIN_MARK))
    }
}
