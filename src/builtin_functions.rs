/// Whether `name` is one of [`BUILTIN_FUNCTION_NAMES`].
// Cost: O(len(name)) -- one hash probe; the slice it indexes is ~150 names,
// which a linear `contains` compared one by one on every call.
pub(crate) fn is_builtin_function(name: &str) -> bool {
    static NAMES: std::sync::OnceLock<rustc_hash::FxHashSet<&'static str>> =
        std::sync::OnceLock::new();
    NAMES
        .get_or_init(|| BUILTIN_FUNCTION_NAMES.iter().copied().collect())
        .contains(name)
}
