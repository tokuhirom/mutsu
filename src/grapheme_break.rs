//! Extended grapheme-cluster segmentation (UAX #29), Unicode 18 rules.
//!
//! The single segmenter every layer uses (`.chars`, `.comb`, regex atoms,
//! `Units`, ...). It replaces the `unicode-segmentation` crate, which lags the
//! Unicode release roast tracks: Unicode 18 changed GB9c (an Indic virama
//! `InCB=Linker` no longer needs a leading consonant to join the consonant
//! after it) and added linkers/consonants.
//!
//! Differences from plain UAX #29, both from Rakudo's NFG:
//! * a utf8-c8 synthetic (`U+10FFFD x H H`, see `runtime::utf8_c8`) is one
//!   cluster on its own and breaks on both sides, like a control character;
//! * a bare `U+10FFFD` behaves as a control as well.
//!
//! Data: `grapheme_break_data.rs`, generated by
//! `scripts/gen-grapheme-break-data.py`. The class byte packs the
//! Grapheme_Cluster_Break value (bits 0-3), Extended_Pictographic (bit 4) and
//! Indic_Conjunct_Break (bits 5-6).

use crate::grapheme_break_data::TABLE;
/// The utf8-c8 synthetic marker; `runtime::utf8_c8` re-exports it.
pub(crate) const SYNTHETIC_MARKER: char = '\u{10FFFD}';

const OTHER: u8 = 0;
const CR: u8 = 1;
const LF: u8 = 2;
const CONTROL: u8 = 3;
const EXTEND: u8 = 4;
const ZWJ: u8 = 5;
const REGIONAL: u8 = 6;
const PREPEND: u8 = 7;
const SPACING: u8 = 8;
const HANGUL_L: u8 = 9;
const HANGUL_V: u8 = 10;
const HANGUL_T: u8 = 11;
const HANGUL_LV: u8 = 12;
const HANGUL_LVT: u8 = 13;
const GCB_MASK: u8 = 0x0F;
const EXT_PICT: u8 = 0x10;
const INCB_SHIFT: u8 = 5;
const INCB_LINKER: u8 = 1;
const INCB_CONSONANT: u8 = 2;
const INCB_EXTEND: u8 = 3;

// Cost: O(log t), t = ranges in the table (constant: ~1500); O(1) for ASCII.
fn class_of(c: char) -> u8 {
    let cp = c as u32;
    if cp < 0x80 {
        return match c {
            '\r' => CR,
            '\n' => LF,
            c if c.is_ascii_control() => CONTROL,
            _ => OTHER,
        };
    }
    let i = TABLE.partition_point(|&(_, hi, _)| hi < cp);
    match TABLE.get(i) {
        Some(&(lo, _, class)) if lo <= cp => class,
        _ => OTHER,
    }
}

/// The cluster-assembly state carried across the codepoints of one cluster.
struct State {
    prev: u8,
    /// 0 none, 1 `ExtPict Extend*` seen, 2 `ExtPict Extend* ZWJ` seen (GB11).
    pict: u8,
    /// Whether `Linker InCB=Extend*` is what the cluster currently ends in (GB9c).
    linker: bool,
    /// Consecutive Regional_Indicators ending the cluster (GB12/13).
    ri: u32,
}

impl State {
    fn start(class: u8) -> State {
        let mut st = State {
            prev: 0,
            pict: 0,
            linker: false,
            ri: 0,
        };
        st.push(class);
        st
    }

    fn push(&mut self, class: u8) {
        let gcb = class & GCB_MASK;
        let incb = class >> INCB_SHIFT;
        self.pict = if class & EXT_PICT != 0 || (self.pict == 1 && gcb == EXTEND) {
            1
        } else if self.pict == 1 && gcb == ZWJ {
            2
        } else {
            0
        };
        self.linker = incb == INCB_LINKER || (self.linker && incb == INCB_EXTEND);
        self.ri = if gcb == REGIONAL { self.ri + 1 } else { 0 };
        self.prev = gcb;
    }

    /// True when there is no boundary between the cluster so far and `class`.
    fn joins(&self, class: u8) -> bool {
        let prev = self.prev;
        let cur = class & GCB_MASK;
        if prev == CR && cur == LF {
            return true; // GB3
        }
        if matches!(prev, CONTROL | CR | LF) || matches!(cur, CONTROL | CR | LF) {
            return false; // GB4, GB5
        }
        match (prev, cur) {
            (HANGUL_L, HANGUL_L | HANGUL_V | HANGUL_LV | HANGUL_LVT) => return true, // GB6
            (HANGUL_LV | HANGUL_V, HANGUL_V | HANGUL_T) => return true,              // GB7
            (HANGUL_LVT | HANGUL_T, HANGUL_T) => return true,                        // GB8
            _ => {}
        }
        if matches!(cur, EXTEND | ZWJ | SPACING) || prev == PREPEND {
            return true; // GB9, GB9a, GB9b
        }
        if self.linker && class >> INCB_SHIFT == INCB_CONSONANT {
            return true; // GB9c
        }
        if self.pict == 2 && class & EXT_PICT != 0 {
            return true; // GB11
        }
        cur == REGIONAL && self.ri % 2 == 1 // GB12, GB13
    }
}

fn is_hex_byte(b: u8) -> bool {
    b.is_ascii_hexdigit()
}

/// The byte length of the utf8-c8 synthetic `U+10FFFD x H H` at the start of
/// `rest`, or of the lone marker when it is not followed by `x H H`.
fn synthetic_len(rest: &[u8]) -> usize {
    let marker = SYNTHETIC_MARKER.len_utf8();
    match rest.get(marker..marker + 3) {
        Some([b'x', h1, h2]) if is_hex_byte(*h1) && is_hex_byte(*h2) => marker + 3,
        _ => marker,
    }
}

/// Byte length of the grapheme cluster at the start of the non-empty `s`.
// Cost: O(k), k = codepoints in the cluster.
pub(crate) fn next_cluster_len(s: &str) -> usize {
    let mut it = s.char_indices();
    let Some((_, first)) = it.next() else {
        return 0;
    };
    if first == SYNTHETIC_MARKER {
        return synthetic_len(s.as_bytes());
    }
    let mut state = State::start(class_of(first));
    for (i, c) in it {
        if c == SYNTHETIC_MARKER {
            return i;
        }
        let class = class_of(c);
        if !state.joins(class) {
            return i;
        }
        state.push(class);
    }
    s.len()
}

/// Iterator over the extended grapheme clusters of a `&str`.
#[derive(Clone)]
pub(crate) struct Graphemes<'a> {
    rest: &'a str,
}

impl<'a> Iterator for Graphemes<'a> {
    type Item = &'a str;

    // Cost: O(k), k = codepoints in the cluster.
    fn next(&mut self) -> Option<&'a str> {
        if self.rest.is_empty() {
            return None;
        }
        let n = next_cluster_len(self.rest);
        let (g, rest) = self.rest.split_at(n);
        self.rest = rest;
        Some(g)
    }
}

/// Iterator over `(byte offset, cluster)` pairs.
#[derive(Clone)]
pub(crate) struct GraphemeIndices<'a> {
    base: usize,
    len: usize,
    inner: Graphemes<'a>,
}

impl<'a> Iterator for GraphemeIndices<'a> {
    type Item = (usize, &'a str);

    // Cost: O(k), k = codepoints in the cluster.
    fn next(&mut self) -> Option<(usize, &'a str)> {
        let g = self.inner.next()?;
        let off = self.len - self.inner.rest.len() - g.len();
        Some((self.base + off, g))
    }
}

/// `str` extension mirroring the `unicode-segmentation` API shape, so call
/// sites read as before. Only *extended* clusters exist: the flag is accepted
/// for source compatibility and must be `true`.
pub(crate) trait UnicodeSegmentation {
    fn graphemes(&self, extended: bool) -> Graphemes<'_>;
    fn grapheme_indices(&self, extended: bool) -> GraphemeIndices<'_>;
}

impl UnicodeSegmentation for str {
    // Cost: O(1) to create; O(n) to drain, n = bytes.
    fn graphemes(&self, extended: bool) -> Graphemes<'_> {
        debug_assert!(extended, "only extended grapheme clusters are supported");
        Graphemes { rest: self }
    }

    // Cost: O(1) to create; O(n) to drain, n = bytes.
    fn grapheme_indices(&self, extended: bool) -> GraphemeIndices<'_> {
        GraphemeIndices {
            base: 0,
            len: self.len(),
            inner: self.graphemes(extended),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn count(s: &str) -> usize {
        s.graphemes(true).count()
    }

    #[test]
    fn unicode_18_conjunct_without_leading_consonant() {
        assert_eq!(count("\u{94D}\u{915}"), 1);
        assert_eq!(count("\u{94D}\u{308}\u{915}"), 1);
        assert_eq!(count("a\u{94D}\u{924}"), 1);
        assert_eq!(count("\u{1CF5}\u{915}"), 1);
        assert_eq!(count("a\u{94D}b"), 2);
    }

    #[test]
    fn synthetic_breaks_on_both_sides() {
        let syn = "\u{10FFFD}xFF";
        assert_eq!(count(&format!("{syn}\u{20E7}")), 2);
        assert_eq!(count(&format!("a{syn}\u{200D}")), 3);
        assert_eq!(count(&format!("{syn}{syn}")), 2);
        assert_eq!(count("\u{10FFFD}\u{20E7}"), 2);
    }

    #[test]
    fn basics() {
        assert_eq!(count("\r\n"), 1);
        assert_eq!(count("a\u{301}b"), 2);
        assert_eq!(count("\u{1F1EF}\u{1F1F5}\u{1F1EF}"), 2);
        assert_eq!(count("\u{1FAEB}\u{200D}\u{1FACC}"), 1);
        let v: Vec<_> = "ab\u{301}".grapheme_indices(true).collect();
        assert_eq!(v, vec![(0, "a"), (1, "b\u{301}")]);
    }
}
