/// Age of a codepoint (`"1.1"` .. latest, or `"Unassigned"`).
// Cost: O(log R), R = number of runs in the table.
pub(super) fn unicode_age(cp: u32) -> &'static str {
    match AGE_RANGES.binary_search_by(|&(lo, hi, _)| {
        if cp < lo {
            std::cmp::Ordering::Greater
        } else if cp > hi {
            std::cmp::Ordering::Less
        } else {
            std::cmp::Ordering::Equal
        }
    }) {
        Ok(i) => AGE_RANGES[i].2,
        Err(_) => "Unassigned",
    }
}
